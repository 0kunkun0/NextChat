export function ChatAction(props: {
  text: string;
  icon: JSX.Element;
  onClick: () => void;
}) {
  const iconRef = useRef<HTMLDivElement>(null);
  const textRef = useRef<HTMLDivElement>(null);
  const [width, setWidth] = useState({
    full: 16,
    icon: 16,
  });

  function updateWidth() {
    if (!iconRef.current || !textRef.current) return;
    const getWidth = (dom: HTMLDivElement) => dom.getBoundingClientRect().width;
    const textWidth = getWidth(textRef.current);
    const iconWidth = getWidth(iconRef.current);
    setWidth({
      full: textWidth + iconWidth,
      icon: iconWidth,
    });
  }

  return (
    <div
      className={clsx(styles["chat-input-action"], "clickable")}
      onClick={() => {
        props.onClick();
        setTimeout(updateWidth, 1);
      }}
      onMouseEnter={updateWidth}
      onTouchStart={updateWidth}
      style={
        {
          "--icon-width": `${width.icon}px`,
          "--full-width": `${width.full}px`,
        } as React.CSSProperties
      }
    >
      <div ref={iconRef} className={styles["icon"]}>
        {props.icon}
      </div>
      <div className={styles["text"]} ref={textRef}>
        {props.text}
      </div>
    </div>
  );
}

function useScrollToBottom(
  scrollRef: RefObject<HTMLDivElement>,
  detach: boolean = false,
  messages: ChatMessage[],
) {
  // for auto-scroll
  const [autoScroll, setAutoScroll] = useState(true);

  /**
   * 本次流式输出是否已经“停在气泡顶部”。
   * 一旦钉住就不再自动滚动，直到用户主动要求回到底部（点按钮 / 发新消息 /
   * 重新生成）——否则生成结束那一刻会突然跳到底部，把正在看的位置弄丢。
   */
  const pinnedRef = useRef(false);

  const scrollDomToBottom = useCallback(() => {
    const dom = scrollRef.current;
    if (dom) {
      requestAnimationFrame(() => {
        pinnedRef.current = false;
        setAutoScroll(true);
        dom.scrollTo(0, dom.scrollHeight);
      });
    }
  }, [scrollRef]);

  /**
   * 流式输出时跟随新内容，但**最多只把“正在生成的那条消息”的顶部滚到画面顶部**。
   *
   * 超过一屏之后就停住（pinnedRef），既不会被新内容一直往下带，
   * 生成结束也不会突然跳到底部。
   */
  const scrollToStreamingMessage = useCallback(() => {
    const dom = scrollRef.current;
    if (!dom) return;

    requestAnimationFrame(() => {
      if (pinnedRef.current) return;

      const el = dom.querySelector<HTMLElement>('[data-streaming="1"]');

      if (!el) {
        dom.scrollTop = dom.scrollHeight - dom.clientHeight;
        return;
      }

      const domRect = dom.getBoundingClientRect();
      const elRect = el.getBoundingClientRect();
      // 消息顶部在滚动内容里的位置
      const messageTop = elRect.top - domRect.top + dom.scrollTop;
      const { target, atCap } = getStreamingScrollTarget({
        clientHeight: dom.clientHeight,
        scrollHeight: dom.scrollHeight,
        messageTop,
      });

      if (atCap) {
        // 气泡已经超过一屏：最多滚到“顶部贴住画面顶部”，然后停住。
        // 只往下滚（target 比当前更靠下才动），不会把用户往回拽
        if (target > dom.scrollTop + 1) {
          dom.scrollTop = target;
        }
        pinnedRef.current = true;
        return;
      }

      // 还没到一屏：正常跟着底部走
      if (target > dom.scrollTop + 1) {
        dom.scrollTop = target;
      }
    });
  }, [scrollRef]);

  // auto scroll
  useEffect(() => {
    // 正在流式输出时只要用户没主动往上翻（autoScroll 为 true）就跟随，
    // 但只在气泡还没超过一屏时贴到底（见 scrollToStreamingMessage）
    const streaming = messages.some((m) => m.streaming);
    if (!autoScroll) return;

    if (streaming) {
      scrollToStreamingMessage();
      return;
    }

    // 停在气泡顶部的情况：生成结束后保持原位置，不要跳到底部
    if (!detach && !pinnedRef.current) {
      scrollDomToBottom();
    }
  });

  // auto scroll when messages length changes
  const lastMessagesLength = useRef(messages.length);
  useEffect(() => {
    if (messages.length > lastMessagesLength.current && !detach) {
      scrollDomToBottom();
    }
    lastMessagesLength.current = messages.length;
  }, [messages.length, detach, scrollDomToBottom]);

  return {
    scrollRef,
    autoScroll,
    setAutoScroll,
    scrollDomToBottom,
  };
}

/**
 * iOS 15 及更早的 Safari 不认 `overscroll-behavior`：
 * 消息列表滚到顶/底之后继续拖动，整个页面会跟着“回弹”。
 *
 * 支持该属性的浏览器交给 CSS 处理；不支持的才挂这个兜底：
 * 到达边缘时拦掉 touchmove，让列表停在原地。
 */
function usePreventOverscroll(ref: RefObject<HTMLDivElement>) {
  useEffect(() => {
    const dom = ref.current;
    if (!dom) return;

    if (
      typeof CSS !== "undefined" &&
      typeof CSS.supports === "function" &&
      CSS.supports("overscroll-behavior", "none")
    ) {
      return;
    }

    let startY = 0;

    const onTouchStart = (e: TouchEvent) => {
      startY = e.touches[0]?.clientY ?? 0;
    };

    const onTouchMove = (e: TouchEvent) => {
      const y = e.touches[0]?.clientY ?? 0;
      const delta = y - startY;
      const atTop = dom.scrollTop <= 0;
      const atBottom = dom.scrollTop + dom.clientHeight >= dom.scrollHeight - 1;

      // 手指往下拉（delta > 0）且已经在顶部 / 手指往上推且已经在底部
      if ((atTop && delta > 0) || (atBottom && delta < 0)) {
        e.preventDefault();
      }
    };

    dom.addEventListener("touchstart", onTouchStart, { passive: true });
    dom.addEventListener("touchmove", onTouchMove, { passive: false });

    return () => {
      dom.removeEventListener("touchstart", onTouchStart);
      dom.removeEventListener("touchmove", onTouchMove);
    };
  }, [ref]);
}

